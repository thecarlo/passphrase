// Generator for words_gen.go. Run via: go generate ./internal/diceware/...
package main

import (
	"bufio"
	"fmt"
	"os"
	"strings"
)

func main() {
	in, err := os.Open("eff_large_wordlist.txt")
	if err != nil {
		fmt.Fprintf(os.Stderr, "gen: open wordlist: %v\n", err)
		os.Exit(1)
	}
	defer in.Close()

	var words []string
	scanner := bufio.NewScanner(in)
	for scanner.Scan() {
		parts := strings.Fields(scanner.Text())
		if len(parts) >= 2 {
			words = append(words, parts[len(parts)-1])
		}
	}
	if err := scanner.Err(); err != nil {
		fmt.Fprintf(os.Stderr, "gen: scan: %v\n", err)
		os.Exit(1)
	}

	out, err := os.Create("words_gen.go")
	if err != nil {
		fmt.Fprintf(os.Stderr, "gen: create output: %v\n", err)
		os.Exit(1)
	}
	defer out.Close()

	w := bufio.NewWriter(out)
	fmt.Fprintln(w, "// Code generated by go generate; DO NOT EDIT.")
	fmt.Fprintln(w, "")
	fmt.Fprintln(w, "package diceware")
	fmt.Fprintln(w, "")
	fmt.Fprintf(w, "var words = []string{\n")
	for _, word := range words {
		fmt.Fprintf(w, "\t%q,\n", word)
	}
	fmt.Fprintln(w, "}")

	if err := w.Flush(); err != nil {
		fmt.Fprintf(os.Stderr, "gen: flush: %v\n", err)
		os.Exit(1)
	}
}
